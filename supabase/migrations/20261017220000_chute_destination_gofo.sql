-- Chute settings changed on the 2026-10-18 ops day (NJSUB-202610171930).
-- New settings live in chute_destination_gofo.
-- chute_destination stays as history and is not used to map that day or later.

CREATE TABLE IF NOT EXISTS public.chute_destination_gofo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chute_id integer NOT NULL REFERENCES public.chute_structure (chute_id),
  warehouse text,
  city text,
  route text,
  region text,
  sort_type text,
  effective_date date NOT NULL,
  note text,
  CONSTRAINT chute_destination_gofo_chk_all_rules CHECK (
    (
      note = ANY (ARRAY['idle'::text, 'block'::text])
      AND warehouse IS NULL
      AND city IS NULL
      AND route = '000000'
      AND region IS NULL
      AND sort_type IS NULL
    )
    OR (
      note IS DISTINCT FROM 'idle'::text
      AND note IS DISTINCT FROM 'block'::text
      AND warehouse IS NOT NULL
      AND region IS NOT NULL
      AND sort_type = ANY (ARRAY['transit'::text, 'last_mile'::text, 'GOFO'::text])
    )
  )
);

CREATE INDEX IF NOT EXISTS chute_destination_gofo_chute_effective_idx
  ON public.chute_destination_gofo (chute_id, effective_date DESC);

COMMENT ON TABLE public.chute_destination_gofo IS
  'Chute settings from ops day 2026-10-18 onward. chute_destination is historical only.';

CREATE OR REPLACE FUNCTION public.trg_chute_destination_gofo_consistency()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
  sibling record;
BEGIN
  IF NEW.note IN ('idle', 'block') THEN
    IF EXISTS (
      SELECT 1
      FROM public.chute_destination_gofo d
      WHERE d.chute_id = NEW.chute_id
        AND d.effective_date = NEW.effective_date
        AND (TG_OP = 'INSERT' OR d.ctid <> NEW.ctid)
        AND COALESCE(d.note, '') NOT IN ('idle', 'block')
    ) THEN
      RAISE EXCEPTION
        'chute_id % on % is disabled (note=%) but active destination rows already exist',
        NEW.chute_id, NEW.effective_date, NEW.note;
    END IF;
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.chute_destination_gofo d
    WHERE d.chute_id = NEW.chute_id
      AND d.effective_date = NEW.effective_date
      AND (TG_OP = 'INSERT' OR d.ctid <> NEW.ctid)
      AND d.note IN ('idle', 'block')
  ) THEN
    RAISE EXCEPTION
      'chute_id % on % is disabled; cannot insert or update an active destination row',
      NEW.chute_id, NEW.effective_date;
  END IF;

  SELECT d.region, d.sort_type
  INTO sibling
  FROM public.chute_destination_gofo d
  WHERE d.chute_id = NEW.chute_id
    AND d.effective_date = NEW.effective_date
    AND (TG_OP = 'INSERT' OR d.ctid <> NEW.ctid)
    AND COALESCE(d.note, '') NOT IN ('idle', 'block')
  LIMIT 1;

  IF FOUND THEN
    IF NEW.region IS DISTINCT FROM sibling.region
       OR NEW.sort_type IS DISTINCT FROM sibling.sort_type
    THEN
      RAISE EXCEPTION
        'inconsistent destination for chute_id % on %: existing (region=%, sort_type=%) vs new (region=%, sort_type=%)',
        NEW.chute_id,
        NEW.effective_date,
        sibling.region,
        sibling.sort_type,
        NEW.region,
        NEW.sort_type;
    END IF;
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS chute_destination_gofo_consistency
  ON public.chute_destination_gofo;
CREATE TRIGGER chute_destination_gofo_consistency
  BEFORE INSERT OR UPDATE ON public.chute_destination_gofo
  FOR EACH ROW
  EXECUTE FUNCTION public.trg_chute_destination_gofo_consistency();

ALTER TABLE public.chute_destination_gofo ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS chute_destination_gofo_select_authenticated
  ON public.chute_destination_gofo;
CREATE POLICY chute_destination_gofo_select_authenticated
  ON public.chute_destination_gofo
  FOR SELECT
  TO authenticated
  USING (true);

GRANT SELECT ON public.chute_destination_gofo TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.chute_destination_gofo TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.chute_destination_gofo_id_seq TO service_role;

DROP FUNCTION IF EXISTS public.city_volume_series(text);

CREATE FUNCTION public.city_volume_series(p_subbatch text DEFAULT NULL)
RETURNS TABLE (
  subbatch text,
  subbatch_date date,
  scraped_at timestamptz,
  city text,
  total_volume bigint,
  delta_volume bigint
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH chosen AS (
    SELECT COALESCE(
      NULLIF(btrim(p_subbatch), ''),
      (SELECT s.subbatch FROM public.subbatch s ORDER BY s.scraped_at DESC LIMIT 1)
    ) AS subbatch
  ),
  batch_meta AS (
    SELECT DISTINCT ON (s.subbatch)
      s.subbatch,
      s.subbatch_date
    FROM public.subbatch s
    JOIN chosen c ON c.subbatch = s.subbatch
    ORDER BY s.subbatch, s.scraped_at DESC
  ),
  meta AS (
    SELECT subbatch, subbatch_date FROM batch_meta
    UNION
    SELECT i.subbatch_id, i.operation_date
    FROM public.city_initial_volume i
    JOIN chosen c ON c.subbatch = i.subbatch_id
    WHERE NOT EXISTS (SELECT 1 FROM batch_meta)
  ),
  initials AS (
    SELECT
      i.subbatch_id,
      i.city,
      i.initial_volume,
      i.scraped_at AS initial_scraped_at
    FROM public.city_initial_volume i
    JOIN chosen c ON c.subbatch = i.subbatch_id
    WHERE EXTRACT(HOUR FROM (i.scraped_at AT TIME ZONE 'America/New_York')) = 21
      AND EXTRACT(MINUTE FROM (i.scraped_at AT TIME ZONE 'America/New_York')) >= 30
      AND EXTRACT(MINUTE FROM (i.scraped_at AT TIME ZONE 'America/New_York')) < 50
  ),
  destinations AS (
    SELECT
      d.chute_id,
      d.warehouse,
      d.city,
      d.sort_type,
      d.effective_date,
      d.id,
      'legacy'::text AS source
    FROM public.chute_destination d
    UNION ALL
    SELECT
      d.chute_id,
      d.warehouse,
      d.city,
      d.sort_type,
      d.effective_date,
      d.id,
      'gofo'::text AS source
    FROM public.chute_destination_gofo d
  ),
  chute_map AS (
    SELECT DISTINCT ON (m.subbatch, d.chute_id)
      m.subbatch,
      d.chute_id,
      CASE
        WHEN lower(coalesce(d.sort_type, '')) = 'transit'
          THEN NULLIF(btrim(d.warehouse), '')
        ELSE NULLIF(btrim(d.city), '')
      END AS city
    FROM meta m
    JOIN destinations d
      ON d.effective_date <= m.subbatch_date
     AND (
       (m.subbatch_date < DATE '2026-10-18' AND d.source = 'legacy')
       OR (m.subbatch_date >= DATE '2026-10-18' AND d.source = 'gofo')
     )
    ORDER BY m.subbatch, d.chute_id, d.effective_date DESC NULLS LAST, d.id DESC
  ),
  snaps AS (
    SELECT
      cv.subbatch_id,
      cv.scraped_at,
      cv.chute_id,
      cv.volume,
      lag(cv.volume) OVER (
        PARTITION BY cv.subbatch_id, cv.chute_id
        ORDER BY cv.scraped_at
      ) AS prev_volume
    FROM public.chute_volume cv
    JOIN chosen c ON c.subbatch = cv.subbatch_id
  ),
  chute_city AS (
    SELECT
      m.subbatch,
      m.subbatch_date,
      s.scraped_at,
      COALESCE(cm.city, 'Unmapped') AS city,
      sum(s.volume)::bigint AS chute_volume,
      sum(GREATEST(s.volume - COALESCE(s.prev_volume, 0), 0))::bigint AS delta_volume
    FROM snaps s
    JOIN meta m ON m.subbatch = s.subbatch_id
    LEFT JOIN chute_map cm
      ON cm.subbatch = s.subbatch_id
     AND cm.chute_id = s.chute_id
    GROUP BY m.subbatch, m.subbatch_date, s.scraped_at, COALESCE(cm.city, 'Unmapped')
  ),
  initial_only AS (
    SELECT
      i.subbatch_id AS subbatch,
      coalesce(m.subbatch_date, i2.operation_date) AS subbatch_date,
      i.initial_scraped_at AS scraped_at,
      i.city,
      i.initial_volume AS total_volume,
      i.initial_volume AS delta_volume
    FROM initials i
    JOIN public.city_initial_volume i2
      ON i2.subbatch_id = i.subbatch_id AND i2.city = i.city
    LEFT JOIN meta m ON m.subbatch = i.subbatch_id
    WHERE NOT EXISTS (SELECT 1 FROM snaps)
  ),
  with_initials AS (
    SELECT
      cc.subbatch,
      cc.subbatch_date,
      cc.scraped_at,
      cc.city,
      (cc.chute_volume + COALESCE(i.initial_volume, 0))::bigint AS total_volume,
      cc.delta_volume
    FROM chute_city cc
    LEFT JOIN initials i
      ON i.subbatch_id = cc.subbatch
     AND i.city = cc.city
  )
  SELECT * FROM with_initials
  UNION ALL
  SELECT * FROM initial_only
  ORDER BY scraped_at, city;
$$;

COMMENT ON FUNCTION public.city_volume_series(text) IS
  'City/hub series. Ops days before 2026-10-18 map through chute_destination. From 2026-10-18, map through chute_destination_gofo only.';

GRANT EXECUTE ON FUNCTION public.city_volume_series(text) TO service_role, authenticated, anon;

